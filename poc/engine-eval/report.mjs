// Renders results/results.json as results/SUMMARY.md (the evidence cited by
// docs/ENGINE_EVALUATION.md).
import { readFile, writeFile } from 'node:fs/promises';
import os from 'node:os';

const report = JSON.parse(await readFile('results/results.json', 'utf8'));
const adapters = Object.entries(report.adapters);
const fixtures = adapters[0][1].rows.map((r) => r.fixture);
const median = (xs) => [...xs].sort((a, b) => a - b)[Math.floor(xs.length / 2)];

const cell = (row) => {
  if (!row) return 'n/a';
  if (row.status === 'rejected') return '✅ rejected cleanly';
  if (row.status === 'kept') return '✅ kept';
  if (row.status === 'lossy') return `⚠️ lost: ${row.lost.join(', ')}`;
  return `❌ ${row.status}`;
};

const lines = [
  '# Round-trip results',
  '',
  `Generated by \`node run.mjs && node report.mjs\`. Node ${report.node}, ${report.platform}, ${os.cpus()[0].model}, ${Math.round(os.totalmem() / 2 ** 30)} GB RAM.`,
  '',
  '"kept" means every inspected feature in the saved file matches the original, after the one requested edit. ' +
    'It is a structural check (see `lib/inspect.mjs`), not a visual comparison.',
  '',
  `| Fixture | ${adapters.map(([, a]) => a.label).join(' | ')} |`,
  `| --- | ${adapters.map(() => '---').join(' | ')} |`,
  ...fixtures.map((f) => `| ${f} | ${adapters.map(([, a]) => cell(a.rows.find((r) => r.fixture === f))).join(' | ')} |`),
  '',
  '## Checks beyond feature comparison',
  '',
  '| Check | ' + adapters.map(([, a]) => a.label).join(' | ') + ' |',
  '| --- | ' + adapters.map(() => '---').join(' | ') + ' |',
];

const saved = (a) => a.rows.filter((r) => r.outFile);
const checks = {
  'Edit persisted after reopen': (a) => `${saved(a).filter((r) => !r.lost?.includes('editPersisted')).length}/${saved(a).length}`,
  'Saved file reopens in same engine': (a) => `${saved(a).filter((r) => !r.reopenError).length}/${saved(a).length}`,
  'Saved file opens in LibreOffice': (a) => `${saved(a).filter((r) => r.libreoffice === 'opened').length}/${saved(a).length}`,
  'LibreOffice shows the edit': (a) => `${saved(a).filter((r) => r.libreofficeSeesEdit).length}/${saved(a).filter((r) => r.fixture !== 'empty-document').length}`,
  'Malformed inputs rejected without crash': (a) => `${a.rows.filter((r) => r.fixture.startsWith('malformed') && r.status === 'rejected').length}/3`,
  'Network attempts (blocked)': (a) => String(a.networkAttempts.length),
  'Small fixture open, median ms': (a) => median(saved(a).filter((r) => r.fixture !== 'long-document').map((r) => r.openMs)).toFixed(0),
  'Long document (2,000 paragraphs) open, median of 5, ms': (a) => a.longDocumentTiming.openMsMedian.toFixed(0),
  'Long document save, median of 5, ms': (a) => a.longDocumentTiming.saveMsMedian.toFixed(0),
};
for (const [name, fn] of Object.entries(checks)) lines.push(`| ${name} | ${adapters.map(([, a]) => fn(a)).join(' | ')} |`);

lines.push('', '## Differences found', '');
for (const [, a] of adapters) {
  const lossy = a.rows.filter((r) => r.diffs && Object.keys(r.diffs).length);
  if (!lossy.length) continue;
  lines.push(`### ${a.label}`, '');
  for (const row of lossy) {
    for (const [key, d] of Object.entries(row.diffs)) {
      lines.push(`- **${row.fixture}**, \`${key}\`: expected \`${JSON.stringify(d.expected)}\`, got \`${JSON.stringify(d.actual)}\``);
    }
  }
  lines.push('');
}

await writeFile('results/SUMMARY.md', lines.join('\n'));
console.log(lines.join('\n'));
